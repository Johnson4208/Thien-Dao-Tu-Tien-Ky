import assert from 'node:assert/strict';
import {newGame,applyAction,decodeSave,stats,refreshTraining} from '../engine.js';
const at=1700000000000;
let state=newGame(at);
for(let i=0;i<3;i++) assert(applyAction(state,'gather','',at+i).ok);
assert.equal(state.bag.herb,6);assert.equal(state.energy,6);
assert(applyAction(state,'craft','qiPill',at+5).ok);
assert.equal(state.bag.qiPill,1);assert.equal(state.bag.herb,3);
assert(applyAction(state,'forge','sword',at+6).ok);
assert.equal(stats(state).attack,26);assert.equal(state.bag.ore,1);assert.equal(state.counts.forge,1);
assert(applyAction(state,'claim','forge',at+7).ok);
const stones=state.stones;assert(!applyAction(state,'claim','forge',at+8).ok);assert.equal(state.stones,stones);
state=decodeSave(JSON.stringify(state));assert.equal(state.gear.sword,1);assert(state.claimed.includes('forge'));
const oldSave={...state,counts:{...state.counts,forge:0}};
assert.equal(decodeSave(JSON.stringify(oldSave)).counts.forge,1);
assert(applyAction(state,'practice','mat',at+10).ok);
refreshTraining(state,at+10010);assert.equal(state.xp,20);
assert(!applyAction(state,'craft','qiPill',at+10011).ok);
assert(applyAction(state,'stop-practice','mat',at+10012).ok);
assert(applyAction(state,'seclusion','',at+10013).ok);
assert(!applyAction(state,'seclusion','',at+10014).ok);
assert(applyAction(state,'seclusion','',at+55014).ok);
assert.equal(state.seclusion,null);
console.log('Gather → craft → forge → claim → save → meditate → seclusion passed.');
